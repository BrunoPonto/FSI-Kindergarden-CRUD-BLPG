    private void BRegistroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRegistroActionPerformed

        SimpleDateFormat s = new SimpleDateFormat("yyyy-MM-dd");
        infante kid = new infante(
                txtCurp.getText(),
                txtNombre.getText(),
                cbxSexo.getSelectedItem().toString(),
                s.format((Date) sFecha.getValue()),
                cbxEstado.getSelectedItem().toString()
        );

        if (kid.insertar(cnx.con) == 1) {
            JOptionPane.showMessageDialog(this, "Infante registrado");
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Error de registro");
        }
    }//GEN-LAST:event_BRegistroActionPerformed

