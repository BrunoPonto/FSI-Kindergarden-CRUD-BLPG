    private void BRegitrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BRegitrarActionPerformed
        responsable res = new responsable(
                txtCurp.getText(),
                txtNombre.getText(),
                cbxSexo.getSelectedItem().toString(),
                txtTelefono.getText(),
                txtParentesco.getText(),
                cbxEstado.getSelectedItem().toString()
        );

        if (res.insetar(cnx.con) == 1) {
            JOptionPane.showMessageDialog(this, "Responsable registrado");
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Error de registro");
        }
    }//GEN-LAST:event_BRegitrarActionPerformed

